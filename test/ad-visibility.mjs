import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import vm from 'node:vm';
const context = vm.createContext({ URL, console });
vm.runInContext(readFileSync(new URL('../content/instagram-model.js', import.meta.url), 'utf8'), context);
const filter = context.InstagramDownloaderModel.filterTimelineAds;
const normal = { node: { media: { code: 'normal', caption: 'Sponsored mention in an ordinary caption', is_ad: false } } };
const payload = { data: { xdt_api__v1__feed__timeline: { edges: [normal, { node: { media: { is_ad: true } } }, { node: { media: { ad_id: 'ad1' } } }], page_info: { end_cursor: 'keep', has_next_page: true } } } };
assert.equal(filter(payload, false), 2);
assert.equal(payload.data.xdt_api__v1__feed__timeline.edges[0], normal);
assert.equal(payload.data.xdt_api__v1__feed__timeline.page_info.end_cursor, 'keep');
assert.equal(filter(payload, false), 0);
const detail = { items: [{ is_ad: true }] };
const injected = { data: { xdt_injected_story_units: { ad_media_items: [{ id: 'ad' }], earliest_request_position: 5 } } };
assert.equal(filter(injected, false), 1);
assert.equal(injected.data.xdt_injected_story_units.ad_media_items.length, 0);
assert.equal(injected.data.xdt_injected_story_units.earliest_request_position, 5);
assert.equal(filter(detail, false), 0, 'detail response must remain unchanged');
assert.equal(filter(detail, true), 1);
const organic = { node: { explore_story: { media: { code: 'ordinary' }, ad: null } } };
const connection = { edges: [organic, { node: { media: null, ad: { __typename: 'XDTAd' } } }, { node: { explore_story: { media: {}, ad: { __typename: 'XDTAd' } } } }], page_info: { end_cursor: 'unchanged' } };
const preload = { require: [['ScheduledServerJS', 'handle', null, [{ __bbox: { require: [['RelayPrefetchedStreamCache', 'next', [], [null, { __bbox: { result: { data: { xdt_api__v1__feed__timeline__connection: connection } } } }]]] } }]]] };
assert.equal(filter(preload, false), 2, 'filter the real ScheduledServerJS preload and nested ad units');
assert.equal(connection.edges.length, 1);
assert.equal(connection.edges[0], organic);
assert.equal(connection.page_info.end_cursor, 'unchanged');
console.log('timeline ad filtering, normal posts, pagination and detail isolation passed');
